#######################################
# Repair isolated environment
# Fixes broken symlinks and permissions after git clone
# Returns:
#   0 - success (all repairs successful)
#   1 - errors found that couldn't be fixed
# Side effects:
#   - Recreates npm/npx/corepack symlinks
#   - Recreates Claude Code symlink
#   - Fixes file permissions
#######################################
repair_isolated_environment() {
	echo ""
	echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
	echo "  Repairing Isolated Environment"
	echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
	echo ""

	# Check if isolated environment exists
	if [[ ! -d "$ISOLATED_NVM_DIR" ]]; then
		print_error "Isolated environment not found"
		echo ""
		echo "Directory: $ISOLATED_NVM_DIR"
		echo ""
		echo "Install first with: ./iclaude.sh --isolated-install"
		return 1
	fi

	print_info "Checking isolated environment: $ISOLATED_NVM_DIR"
	echo ""

	local errors=0
	local fixed=0

	# Find Node.js version directory using the same selection as setup_isolated_nvm.
	local node_version_dir
	if declare -F get_isolated_node_version_dir &>/dev/null; then
		node_version_dir=$(get_isolated_node_version_dir "$ISOLATED_NVM_DIR/versions/node")
	else
		node_version_dir=$(find "$ISOLATED_NVM_DIR/versions/node" -maxdepth 1 -type d -name "v*" 2>/dev/null | LC_ALL=C sort | tail -1)
	fi

	if [[ -z "$node_version_dir" ]]; then
		print_error "No Node.js version found in isolated environment"
		return 1
	fi

	local node_version=$(basename "$node_version_dir")
	print_info "Found Node.js version: $node_version"
	echo ""

	# Repair npm/npx/corepack symlinks
	create_npm_symlinks "$node_version_dir" || errors=$((errors + 1))

	# Repair Claude Code symlink
	echo ""
	create_claude_symlink || errors=$((errors + 1))

	# Repair settings.json absolute paths
	echo ""
	print_info "Checking settings.json paths..."
	repair_settings_paths || errors=$((errors + 1))

	# Repair plugin registry files (create known_marketplaces.json if missing after git rm)
	echo ""
	print_info "Checking plugin registry files..."
	if declare -f repair_plugin_paths &>/dev/null; then
		repair_plugin_paths || errors=$((errors + 1))
	fi

	# Repair vendor binary permissions (rg loses +x after git update)
	echo ""
	repair_vendor_permissions || errors=$((errors + 1))

	# Configure git hooks path
	echo ""
	print_info "Checking git hooks configuration..."
	configure_git_hooks || errors=$((errors + 1))

	# Install plugins from manifest (if function is defined and manifest exists)
	if declare -f install_plugins_from_manifest &>/dev/null; then
		echo ""
		print_info "Checking plugins from plugins-manifest.json..."
		install_plugins_from_manifest
	fi

	# Summary
	echo ""
	echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
	if [[ $errors -eq 0 ]]; then
		print_success "Repair completed successfully"
	else
		print_warning "Repair completed with $errors error(s)"
	fi
	echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

	# PII proxy venv is NOT in git — remind user to reinstall after git clone/pull.
	# Check both: venv directory missing AND server script missing (server.py is in git,
	# but the installed copy in config dir is generated by --install-pii-proxy).
	if [[ -n "${PII_PROXY_VENV:-}" ]] && [[ ! -d "$PII_PROXY_VENV" ]]; then
		echo ""
		print_warning "PII proxy not installed (Python venv not included in git)"
		print_info "  Reinstall: ./iclaude.sh --install-pii-proxy  (~500MB, one-time)"
	fi

	echo ""

	return $errors
}

#######################################
# Create npm/npx/corepack symlinks
# Arguments:
#   $1 - Node.js version directory (e.g., /path/to/.nvm-isolated/versions/node/v18.20.8)
# Returns:
#   0 - success
#   1 - errors found
#######################################
create_npm_symlinks() {
	local node_version_dir="$1"

	print_info "Checking Node.js symlinks..."

	# Array of symlinks to check/repair: [link_path]=[target_path]
	declare -A symlinks=(
		["$node_version_dir/bin/npm"]="../lib/node_modules/npm/bin/npm-cli.js"
		["$node_version_dir/bin/npx"]="../lib/node_modules/npm/bin/npx-cli.js"
		["$node_version_dir/bin/corepack"]="../lib/node_modules/corepack/dist/corepack.js"
	)

	local errors=0

	for link_path in "${!symlinks[@]}"; do
		local target="${symlinks[$link_path]}"
		local link_name=$(basename "$link_path")

		# Remove and recreate symlink
		rm -f "$link_path"
		ln -s "$target" "$link_path"

		if [[ -L "$link_path" ]]; then
			print_success "  ✓ Created: $link_name"
		else
			print_error "  ✗ Failed: $link_name"
			errors=$((errors + 1))
		fi
	done

	return $errors
}

#######################################
# Create Claude Code symlink
# Returns:
#   0 - success
#   1 - error
#######################################
create_claude_symlink() {
	print_info "Checking Claude Code symlink..."

	local claude_link="$ISOLATED_NVM_DIR/npm-global/bin/claude"
	local claude_pkg_dir="$ISOLATED_NVM_DIR/npm-global/lib/node_modules/@anthropic-ai/claude-code"
	local claude_bin="$claude_pkg_dir/bin/claude.exe"
	local install_script="$claude_pkg_dir/install.cjs"

	if [[ ! -f "$claude_pkg_dir/package.json" ]]; then
		print_warning "  ! Claude Code not installed yet"
		return 0
	fi

	# Binary is excluded from git (>100MB). Try to regenerate via postinstall.
	# bin/ must exist first — install.cjs hardlinks into it and fails silently if absent.
	if [[ ! -f "$claude_bin" ]] && [[ -f "$install_script" ]]; then
		print_info "  Running postinstall to restore claude binary..."
		mkdir -p "$claude_pkg_dir/bin"
		(cd "$claude_pkg_dir" && node install.cjs 2>/dev/null) || true
	fi

	# If still missing, optional platform package not installed or mismatched version.
	# Install the platform-specific package explicitly — npm install -g (same version)
	# skips optional deps it considers already installed, so we target it directly.
	if [[ ! -f "$claude_bin" ]]; then
		if command -v npm &>/dev/null; then
			local pkg_version os_name arch_name platform_pkg
			pkg_version=$(node -e "process.stdout.write(require('$claude_pkg_dir/package.json').version)" 2>/dev/null)
			os_name=$(uname -s | tr '[:upper:]' '[:lower:]')
			arch_name=$(uname -m)
			case "$arch_name" in
				x86_64)          arch_name="x64" ;;
				aarch64|arm64)   arch_name="arm64" ;;
			esac
			platform_pkg="@anthropic-ai/claude-code-${os_name}-${arch_name}"

			print_info "  Installing platform binary: ${platform_pkg}@${pkg_version}"
			npm install -g "${platform_pkg}@${pkg_version}" 2>&1 | tail -3 || true

			# Re-run postinstall now that platform package is available
			if [[ -f "$install_script" ]]; then
				mkdir -p "$claude_pkg_dir/bin"
				(cd "$claude_pkg_dir" && node install.cjs 2>/dev/null) || true
			fi
		fi
	fi

	if [[ ! -f "$claude_bin" ]]; then
		print_error "  ✗ Native binary not found. Run: ./iclaude.sh --update"
		return 1
	fi

	local relative_target="../lib/node_modules/@anthropic-ai/claude-code/bin/claude.exe"

	mkdir -p "$(dirname "$claude_link")"
	rm -f "$claude_link"
	ln -s "$relative_target" "$claude_link"
	chmod +x "$claude_link"

	if [[ -L "$claude_link" ]]; then
		print_success "  ✓ Created: claude symlink"
		return 0
	else
		print_error "  ✗ Failed: claude symlink"
		return 1
	fi
}

#######################################
# Repair vendor binary permissions
# git stores binaries without execute bit; after git pull/update rg loses +x,
# which breaks Claude Code's bundled ripgrep (used to scan commands/*.md etc.)
# Returns:
#   0 - success
#######################################
repair_vendor_permissions() {
	local vendor_dir="$ISOLATED_NVM_DIR/npm-global/lib/node_modules/@anthropic-ai/claude-code/vendor"
	print_info "Checking vendor binary permissions..."

	if [[ ! -d "$vendor_dir" ]]; then
		# vendor/ was removed in v2.1.114+ (native binary bundles rg internally)
		print_success "  ✓ Vendor dir not present (native binary format, no action needed)"
		return 0
	fi

	local fixed=0
	while IFS= read -r -d '' bin; do
		if [[ ! -x "$bin" ]]; then
			chmod +x "$bin"
			fixed=$((fixed + 1))
		fi
	done < <(find "$vendor_dir" \( -name "rg" -o -name "rg.exe" -o -name "*.node" \) -print0 2>/dev/null)

	if [[ $fixed -gt 0 ]]; then
		print_success "  ✓ Fixed execute bit on $fixed vendor binary(ies)"
	else
		print_success "  ✓ Vendor permissions OK"
	fi
	return 0
}

#######################################
# Repair absolute paths in settings.json
# Migrates legacy hardcoded .claude-isolated paths to $CLAUDE_CONFIG_DIR variable
# (exported by iclaude.sh before launch, inherited by hooks/statusLine subprocesses).
# Handles two legacy formats:
#   1. Absolute paths:      /some/path/.claude-isolated/hooks/...
#   2. $CLAUDE_PROJECT_DIR: $CLAUDE_PROJECT_DIR/.nvm-isolated/.claude-isolated/hooks/...
# Both are replaced with the canonical form: $CLAUDE_CONFIG_DIR/hooks/...
# Called during --repair-isolated for one-time migration of old installs.
# Returns:
#   0 - success (already canonical or migrated)
#   1 - could not migrate
#######################################
repair_settings_paths() {
	local settings_file="$ISOLATED_CONFIG_DIR/settings.json"

	[[ ! -f "$settings_file" ]] && return 0

	# Already using canonical $CLAUDE_CONFIG_DIR everywhere — nothing to do.
	# Excludes non-canonical $CLAUDE_PROJECT_DIR/.nvm-isolated/.claude-isolated form.
	if grep -q '\$CLAUDE_CONFIG_DIR' "$settings_file" 2>/dev/null \
		&& ! grep -q '\$CLAUDE_PROJECT_DIR/\.nvm-isolated/\.claude-isolated' \
		         "$settings_file" 2>/dev/null \
		&& ! grep -o '[^"[:space:]]*\.claude-isolated' "$settings_file" 2>/dev/null \
		       | grep -qv '^\$CLAUDE_CONFIG_DIR'; then
		return 0
	fi

	local temp_file="${settings_file}.tmp"
	cp "$settings_file" "$temp_file"

	# Step 1: migrate $CLAUDE_PROJECT_DIR/.nvm-isolated/.claude-isolated → $CLAUDE_CONFIG_DIR
	sed -i 's|\$CLAUDE_PROJECT_DIR/\.nvm-isolated/\.claude-isolated|\$CLAUDE_CONFIG_DIR|g' \
		"$temp_file"

	# Step 2: migrate any remaining absolute /path/.claude-isolated → $CLAUDE_CONFIG_DIR
	local stale_dir
	stale_dir=$(grep -o '[^"[:space:]]*\.claude-isolated' "$temp_file" 2>/dev/null \
		| sort -u | grep -v '^\$CLAUDE_CONFIG_DIR' | head -1) || true

	if [[ -n "$stale_dir" ]]; then
		print_info "  Migrating settings.json to portable \$CLAUDE_CONFIG_DIR paths"
		print_info "    Was: $stale_dir"
		sed -i "s|${stale_dir}|\$CLAUDE_CONFIG_DIR|g" "$temp_file"
	fi

	if [[ -s "$temp_file" ]]; then
		mv "$temp_file" "$settings_file"
		chmod 600 "$settings_file"
		print_success "  settings.json migrated to portable paths (\$CLAUDE_CONFIG_DIR)"
		return 0
	else
		rm -f "$temp_file"
		print_error "  Failed to migrate settings.json paths"
		return 1
	fi
}

#######################################
# Configure git hooks path
# Sets core.hooksPath to .githooks so shared hooks are active after clone
# Returns:
#   0 - success
#   1 - not a git repository or git not found
#######################################
configure_git_hooks() {
	if ! command -v git &>/dev/null; then
		print_warning "  ! git not found, skipping hooks configuration"
		return 0
	fi

	if ! git -C "$SCRIPT_DIR" rev-parse --git-dir &>/dev/null 2>&1; then
		print_warning "  ! Not a git repository, skipping hooks configuration"
		return 0
	fi

	local hooks_dir="$SCRIPT_DIR/.githooks"
	if [[ ! -d "$hooks_dir" ]]; then
		print_warning "  ! .githooks directory not found, skipping"
		return 0
	fi

	local current
	current=$(git -C "$SCRIPT_DIR" config core.hooksPath 2>/dev/null || true)

	if [[ "$current" == ".githooks" ]]; then
		print_success "  ✓ git hooks path already set to .githooks"
		return 0
	fi

	git -C "$SCRIPT_DIR" config core.hooksPath .githooks
	print_success "  ✓ git hooks path set to .githooks"
	return 0
}
